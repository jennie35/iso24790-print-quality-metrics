# 处理每个图案
for name, bitmap in bitmap_tables.items():
    # 转换为二维数组（0=白，1=黑）
    binary_array = np.array([[int(pixel) for pixel in row] for row in bitmap])

    # 反转颜色：0→255（白），1→0（黑）
    img_array = np.where(binary_array == 0, 255, 0).astype('uint8')

    # 计算位图宽度（像素）
    bitmap_width_px = img_array.shape[1]

    # 计算800 DPI下30毫米对应的像素数
    mm_to_inch = 25.4
    target_length_px = int(30 * (800 / mm_to_inch))  # 30mm at 800 DPI

    # 计算需要重复的次数（至少50次，或满足30mm长度）
    min_repeats = 50
    required_repeats = max(min_repeats, int(np.ceil(target_length_px / bitmap_width_px)))

    # 垂直重复位图 50 次
    repeated_array = np.tile(img_array, (50, 1))


    img = Image.fromarray(repeated_array, 'L')  # 因为是灰度图

    # 设置DPI为800
    img.info['dpi'] = (800, 800)

    # 保存文件
    filename = f"{name}_vertical_repeats_50.png"
    img.save(filename, dpi=(800, 800))

    # 计算实际长度（毫米）
    actual_length_mm = (img.width / 800) * 25.4

    actual_height_mm = (img.height / 800) * 25.4
    print(f"已保存: {filename} (尺寸: {img.width}x{img.height} 像素, 800 DPI)")
    print(f"位图高度: {img.height}px | 实际高度: {actual_height_mm:.1f}mm\n")


